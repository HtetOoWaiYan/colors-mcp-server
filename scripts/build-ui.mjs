// Builds the viewer into one HTML file and embeds it as a TypeScript string module,
// so the published server needs no extra files at runtime.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

execFileSync("npx", ["vite", "build", "--config", "ui/vite.config.ts"], {
	stdio: "inherit",
});
const html = readFileSync("ui/dist/index.html", "utf8");
writeFileSync(
	"src/ui/viewer.generated.ts",
	`// Generated by scripts/build-ui.mjs from ui/. Do not edit.\nexport const VIEWER_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`viewer.generated.ts: ${html.length} bytes`);
